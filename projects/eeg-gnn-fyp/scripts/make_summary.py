"""Turn raw predictions into the tables, statistics and figures used in the report.

  python scripts/make_summary.py --results results
  python scripts/make_summary.py --results results_synthetic --synthetic     # stamps figures as test output
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from eegfyp import plots  # noqa: E402
from eegfyp.evaluate import holm_correction, paired_wilcoxon, summarize  # noqa: E402

COMPARISONS = [
    ("csp_lda", "csp_lda_permuted"), ("eegnet", "csp_lda"), ("gcn_distance", "gcn_identity"),
    ("gcn_corr", "gcn_identity"), ("gcn_plv", "gcn_identity"), ("gcn_uniform", "gcn_identity"),
    ("gcn_random", "gcn_identity"), ("gcn_distance", "gcn_random"), ("gcn_distance", "gcn_uniform"),
    ("gcn_distance", "eegnet"), ("gcn_distance", "csp_lda"),
]


def fmt(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, r in df.iterrows():
        cells = []
        for c, v in r.items():
            if isinstance(v, float) and c.startswith("p_"):
                cells.append("<0.001" if v < 0.001 else f"{v:.3f}")
            else:
                cells.append(f"{v:.3f}" if isinstance(v, float) else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--synthetic", action="store_true")
    args = ap.parse_args()
    root = Path(args.results)
    files = sorted(root.glob("*/preds*.csv"))
    if not files:
        sys.exit(f"No preds*.csv found under {root}/*/ - run the experiments first.")
    preds = pd.concat([pd.read_csv(f) for f in files], ignore_index=True)
    banner = "SYNTHETIC DATA - PIPELINE TEST" if args.synthetic else None
    fig_dir = root / "figures"

    summ = summarize(preds)
    summ.to_csv(root / "summary.csv", index=False)

    present = set(summ["method"])
    comps = [paired_wilcoxon(preds, a, b) for a, b in COMPARISONS if a in present and b in present]
    if comps:
        adj = holm_correction([c["p_value"] for c in comps])
        for c, p in zip(comps, adj):
            c["p_holm"] = p
    comp_df = pd.DataFrame(comps)
    if comps:
        comp_df.to_csv(root / "comparisons.csv", index=False)

    plots.plot_method_comparison(summ, fig_dir / "method_comparison.png", banner)
    real = [m for m in summ["method"] if not m.endswith("_permuted")]
    plots.plot_confusions(preds, real, fig_dir / "confusion_matrices.png", banner)
    if "gcn_distance" in present and "gcn_identity" in present:
        plots.plot_per_subject_scatter(preds, "gcn_distance", "gcn_identity", fig_dir / "scatter_graph_vs_nograph.png", banner)
    if "eegnet" in present and "csp_lda" in present:
        plots.plot_per_subject_scatter(preds, "eegnet", "csp_lda", fig_dir / "scatter_eegnet_vs_csp.png", banner)
    for h in root.glob("*/histories.json"):
        plots.plot_learning_curves(h, fig_dir / "learning_curves.png", banner)

    md = ["# Results summary (auto-generated by scripts/make_summary.py)", ""]
    if args.synthetic:
        md += ["> **SYNTHETIC DATA - pipeline test only. These numbers are NOT research results.**", ""]
    md += ["Protocol: subject-wise cross-validation (test subjects never seen in training). "
           "`subject_acc` = mean per-subject accuracy with 95% bootstrap CI over subjects; "
           "`trial_acc` = trial-level accuracy averaged over seeds.", "",
           fmt(summ.round(3)), ""]
    if comps:
        md += ["## Paired comparisons (Wilcoxon signed-rank on per-subject accuracy, Holm-corrected)", "",
               fmt(comp_df), ""]
    md += ["## Figures", "", "![methods](figures/method_comparison.png)", "![confusion](figures/confusion_matrices.png)", ""]
    (root / "summary.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
